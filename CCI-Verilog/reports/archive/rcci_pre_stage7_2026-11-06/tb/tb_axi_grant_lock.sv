`timescale 1ns/1ps
module tb_axi_grant_lock;
    localparam int ID_WIDTH=4, ADDR_WIDTH=64, DATA_WIDTH=128, INGRESS_IDX_WIDTH=4;
    logic  ACLK;
    logic  ARESETn;
    logic  M0_AWVALID;
    logic  M0_AWREADY;
    logic [ID_WIDTH-1:0] M0_AWID;
    logic [ADDR_WIDTH-1:0] M0_AWADDR;
    logic [7:0] M0_AWLEN;
    logic  M0_WVALID;
    logic  M0_WREADY;
    logic [DATA_WIDTH-1:0] M0_WDATA;
    logic [DATA_WIDTH/8-1:0] M0_WSTRB='1;
    logic  M0_WLAST;
    logic  M0_BVALID;
    logic  M0_BREADY;
    logic [ID_WIDTH-1:0] M0_BID;
    logic [1:0] M0_BRESP;
    logic  M0_ARVALID;
    logic  M0_ARREADY;
    logic [ID_WIDTH-1:0] M0_ARID;
    logic [ADDR_WIDTH-1:0] M0_ARADDR;
    logic [7:0] M0_ARLEN;
    logic  M0_RVALID;
    logic  M0_RREADY;
    logic [ID_WIDTH-1:0] M0_RID;
    logic [DATA_WIDTH-1:0] M0_RDATA;
    logic  M0_RLAST;
    logic [1:0] M0_RRESP;
    logic  M1_AWVALID;
    logic  M1_AWREADY;
    logic [ID_WIDTH-1:0] M1_AWID;
    logic [ADDR_WIDTH-1:0] M1_AWADDR;
    logic [7:0] M1_AWLEN;
    logic  M1_WVALID;
    logic  M1_WREADY;
    logic [DATA_WIDTH-1:0] M1_WDATA;
    logic [DATA_WIDTH/8-1:0] M1_WSTRB='1;
    logic  M1_WLAST;
    logic  M1_BVALID;
    logic  M1_BREADY;
    logic [ID_WIDTH-1:0] M1_BID;
    logic [1:0] M1_BRESP;
    logic  M1_ARVALID;
    logic  M1_ARREADY;
    logic [ID_WIDTH-1:0] M1_ARID;
    logic [ADDR_WIDTH-1:0] M1_ARADDR;
    logic [7:0] M1_ARLEN;
    logic  M1_RVALID;
    logic  M1_RREADY;
    logic [ID_WIDTH-1:0] M1_RID;
    logic [DATA_WIDTH-1:0] M1_RDATA;
    logic  M1_RLAST;
    logic [1:0] M1_RRESP;
    logic  S_AWVALID;
    logic  S_AWREADY;
    logic [ID_WIDTH:0] S_AWID;
    logic [ADDR_WIDTH-1:0] S_AWADDR;
    logic [7:0] S_AWLEN;
    logic  S_WVALID;
    logic  S_WREADY;
    logic [DATA_WIDTH-1:0] S_WDATA;
    logic [DATA_WIDTH/8-1:0] S_WSTRB;
    logic  S_WLAST;
    logic  S_BVALID;
    logic  S_BREADY;
    logic [ID_WIDTH:0] S_BID;
    logic [1:0] S_BRESP;
    logic  S_ARVALID;
    logic  S_ARREADY;
    logic [ID_WIDTH:0] S_ARID;
    logic [ADDR_WIDTH-1:0] S_ARADDR;
    logic [7:0] S_ARLEN;
    logic  S_RVALID;
    logic  S_RREADY;
    logic [ID_WIDTH:0] S_RID;
    logic [DATA_WIDTH-1:0] S_RDATA;
    logic  S_RLAST;
    logic [1:0] S_RRESP;
    logic [INGRESS_IDX_WIDTH-1:0] M1_AWINGRESS_IDX;
    logic [INGRESS_IDX_WIDTH-1:0] M1_BINGRESS_IDX;
    logic  M1_BFIRE;
    logic  axi_idle;
    logic  aw_grant_locked;
    logic  ar_grant_locked;
    logic  aw_locked_route;
    logic  ar_locked_route;
    logic  protocol_error_wlast;
    logic  protocol_error_rlast;
    logic  protocol_error_bid_order;
    logic  protocol_error_rid_order;
    logic  protocol_error_outstanding_overflow;
    axi4_simple_2to1_bus_arbiter dut (.*);
    initial ACLK=0;
    always #5 ACLK=~ACLK;
    initial begin
        ARESETn=0;
        M0_AWVALID=0;
        M0_AWID=0;
        M0_AWADDR=0;
        M0_AWLEN=0;
        M0_WVALID=0;
        M0_WDATA=0;
        M0_WLAST=0;
        M0_BREADY=0;
        M0_ARVALID=0;
        M0_ARID=0;
        M0_ARADDR=0;
        M0_ARLEN=0;
        M0_RREADY=0;
        M1_AWVALID=0;
        M1_AWID=0;
        M1_AWADDR=0;
        M1_AWLEN=0;
        M1_WVALID=0;
        M1_WDATA=0;
        M1_WLAST=0;
        M1_BREADY=0;
        M1_ARVALID=0;
        M1_ARID=0;
        M1_ARADDR=0;
        M1_ARLEN=0;
        M1_RREADY=0;
        S_AWREADY=0;
        S_WREADY=0;
        S_BVALID=0;
        S_BID=0;
        S_BRESP=0;
        S_ARREADY=0;
        S_RVALID=0;
        S_RID=0;
        S_RDATA=0;
        S_RLAST=0;
        S_RRESP=0;
        M1_AWINGRESS_IDX=0;
        repeat(3) @(negedge ACLK); ARESETn=1;
        @(negedge ACLK);
        M1_AWVALID=1; M1_AWID=3; M1_AWADDR=64'h1234_5678_0000_0040; M1_AWLEN=3;
        M1_ARVALID=1; M1_ARID=7; M1_ARADDR=64'hfabc_def0_0000_0080; M1_ARLEN=3;
        repeat(2) @(negedge ACLK);
        M0_AWVALID=1; M0_AWID=2; M0_AWADDR=64'h0040; M0_AWLEN=7;
        M0_ARVALID=1; M0_ARID=6; M0_ARADDR=64'h0080; M0_ARLEN=7;
        repeat(7) begin
            @(negedge ACLK);
            assert(S_AWVALID && S_AWID==5'h13 && S_AWADDR==64'h1234_5678_0000_0040 && S_AWLEN==3)
                else $fatal(1,"stalled AW changed after competing master arrived");
            assert(S_ARVALID && S_ARID==5'h17 && S_ARADDR==64'hfabc_def0_0000_0080 && S_ARLEN==3)
                else $fatal(1,"stalled AR changed after competing master arrived");
        end
        S_AWREADY=1; S_ARREADY=1;
        @(posedge ACLK);
        assert(M1_AWREADY && M1_ARREADY && !M0_AWREADY && !M0_ARREADY) else $fatal(1,"locked grants");
        @(negedge ACLK); M1_AWVALID=0; M1_ARVALID=0;
        @(posedge ACLK);
        assert(M0_AWREADY && M0_ARREADY) else $fatal(1,"round robin resumed");
        @(negedge ACLK); M0_AWVALID=0; M0_ARVALID=0;
        $display("PASS AW/AR grant locks and 64-bit payload stability"); $finish;
    end
endmodule
